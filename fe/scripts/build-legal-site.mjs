/**
 * Renders the public pages (src/features/legal/content.json) into the static
 * site under docs/, for hosting outside the app (GitHub Pages). The app shows
 * the same file at /about, /terms, ..., so edit the JSON, then run:
 *
 *   node fe/scripts/build-legal-site.mjs
 *
 * About Us is the site's index.html; every other page keeps its slug.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const content = JSON.parse(readFileSync(join(here, "../src/features/legal/content.json"), "utf8"));
const out = join(here, "../../docs");
const { business, pages } = content;

const fileOf = (slug) => (slug === "about" ? "index.html" : `${slug}.html`);

const escape = (text) =>
  text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

const fill = (text) => text.replace(/\{(\w+)\}/g, (whole, key) => business[key] ?? whole);

/** App paths become the site's files; mailto: stays as it is. */
function hrefOf(target) {
  if (target === "/") return "index.html";
  if (target.startsWith("/")) return fileOf(target.slice(1));
  return target;
}

/** Filled, escaped text with its [label](target) links as anchors. */
function inline(text) {
  const filled = fill(text);
  const pattern = /\[([^\]]+)\]\(([^)]+)\)/g;
  let html = "";
  let at = 0;
  for (const match of filled.matchAll(pattern)) {
    html += escape(filled.slice(at, match.index));
    html += `<a href="${escape(hrefOf(match[2]))}">${escape(match[1])}</a>`;
    at = match.index + match[0].length;
  }
  return html + escape(filled.slice(at));
}

function block(b) {
  if (typeof b === "string") return `<p>${inline(b)}</p>`;
  if (b.list) return `<ul>\n${b.list.map((item) => `        <li>${inline(item)}</li>`).join("\n")}\n      </ul>`;
  return `<dl class="rows">\n${b.rows
    .map(([label, text]) => `        <div><dt>${inline(label)}</dt><dd>${inline(text)}</dd></div>`)
    .join("\n")}\n      </dl>`;
}

const operatorLine = `${business.brand} is operated by ${business.legalName} (sole proprietor), ${business.city}, ${business.state}, ${business.country}.`;

function render(page) {
  const nav = pages
    .map((p) => `<a href="${fileOf(p.slug)}"${p.slug === page.slug ? ' aria-current="page"' : ""}>${escape(p.short)}</a>`)
    .join("\n        ");
  const footerLinks = pages.map((p) => `<a href="${fileOf(p.slug)}">${escape(p.nav)}</a>`).join("\n      ");
  const sections = page.sections
    .map((s) => `    <section>\n      <h2>${inline(s.heading)}</h2>\n      ${s.blocks.map(block).join("\n      ")}\n    </section>`)
    .join("\n\n");

  return `<!DOCTYPE html>
<!-- Generated by fe/scripts/build-legal-site.mjs from fe/src/features/legal/content.json. Edit the JSON, not this file. -->
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>${escape(page.title)} | ${escape(business.brand)}</title>
  <meta name="description" content="${escape(fill(page.intro))}" />
  <link rel="stylesheet" href="assets/site.css" />
</head>
<body>
  <header class="site">
    <div class="bar">
      <a class="brand" href="index.html">${escape(business.brand)}</a>
      <nav>
        ${nav}
      </nav>
    </div>
  </header>

  <main>
    <h1>${escape(page.title)}</h1>
    <p class="muted">Last updated ${escape(business.lastUpdated)}</p>
    <p class="lede">${inline(page.intro)}</p>

${sections}
  </main>

  <footer class="site">
    <nav>
      ${footerLinks}
    </nav>
    <p>${escape(operatorLine)}</p>
    <p><a href="mailto:${escape(business.email)}">${escape(business.email)}</a> · &copy; ${escape(business.year)} ${escape(business.brand)}</p>
  </footer>
</body>
</html>
`;
}

for (const page of pages) {
  writeFileSync(join(out, fileOf(page.slug)), render(page));
  console.log(`docs/${fileOf(page.slug)}`);
}
